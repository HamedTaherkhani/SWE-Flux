from __future__ import annotations

import pytest

from yt_dlp.pair_trend import trend_read


@pytest.mark.parametrize(
    ("seed", "width", "step"),
    [
        ((0xDEAD ^ 0xDEAD), (0x10 >> 2), (0x01 | 0x00)),
        ((0x10 >> 3), (0x2 << 3), (0x02 << 1)),
        ((0x2 << 1), (0x7F & 0x1E), (0x0F & 0x07)),
        ((0x3C ^ 0x3C), (0x100 >> 5), (0x0A)),
        ((0x7F & 0x1F), (0x3E8 % 0x7D), (0x0D)),
        ((0x100 >> 6), (0x40 >> 4), (0x10)),
        ((0x5A5A ^ 0x5A5A), (0xAA & 0x55), (0x13)),
        ((0x3E8 % 0x7D), (0x33 & 0x0C), (0x16)),
        ((0x40 >> 5), (0xFE ^ 0xFC), (0x19)),
        ((0x11 * 0), (0xCC // 0x66), (0x1C)),
        ((0x0F ^ 0x0D), (0x18 // 0x03), (0x1F)),
        ((0xCC // 0x66), (0x1FF % 0xFD), (0x22)),
        ((0xFE ^ 0xFC), (0x2A ^ 0x0A), (0x25)),
        ((0x200 >> 7), (0x3C ^ 0x0C), (0x28)),
        ((0x33 & 0x0F), (0x10 >> 1), (0x2B)),
        ((0xAA & 0x55), (0x2 << 4), (0x2E)),
        ((0x1FF % 0xFD), (0x5E ^ 0x0E), (0x31)),
        ((0x18 // 0x0C), (0x7F & 0x70), (0x34)),
    ],
)
def test_pair_trend_monotone_probe_cases(seed: int, width: int, step: int) -> None:
    out = trend_read(seed, width, step)
    assert isinstance(out, int)
    assert 0 <= out <= 0xFFFF
