#!/usr/bin/env python3
from __future__ import annotations

import argparse
import ast
import json
import re
from pathlib import Path


def extract_outputs_np(trace_text: str):
    pattern = re.compile(
        r"'outputs_np': 'array\((\[\[\[.*?\]\]\])(?:,\s*dtype=.*?)?\)'",
        re.DOTALL,
    )
    matches = pattern.findall(trace_text)
    if not matches:
        raise ValueError("Could not find `outputs_np` in trace log.")
    matrix_literal = matches[-1].replace("\\n", "\n")
    return ast.literal_eval(matrix_literal)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--trace-log",
        default="/testbed/logs/mha_hard_trace.log",
        help="Path to trace log generated by eval_mha.sh",
    )
    parser.add_argument(
        "--out",
        default="/testbed/logs/mha_hard_qa_oracle.json",
        help="Path to oracle JSON output file",
    )
    args = parser.parse_args()

    trace_path = Path(args.trace_log)
    trace_text = trace_path.read_text(encoding="utf-8")
    oracle_output = extract_outputs_np(trace_text)

    qa = {
        "question_kind": "program_state_prediction",
        "question": (
            "Use `keras/src/test/layers/attention/multi_head_attention_hard_test.py`, "
            "class `MultiHeadAttentionHardTest`, method "
            "`test_cross_attention_with_manual_reference` (lines 9-108). "
            "Setup details: `disable_flash_attention()` on line 10; "
            "`layers.MultiHeadAttention(num_heads=2, key_dim=2, value_dim=2, "
            "use_bias=False, dropout=0.0, output_shape=3)` on lines 12-19; "
            "query/value/key tensors defined on lines 21-52; boolean "
            "`attention_mask` on lines 53-61; layer built on line 63; "
            "query/key/value/output kernels defined on lines 65-98 and assigned "
            "via `layer.set_weights(...)` on line 99; forward call on lines "
            "101-107; `outputs_np = np.array(outputs)` on line 108. "
            "What exact numeric tensor value does `outputs_np` contain?"
        ),
        "oracle_answer": oracle_output,
        "oracle_source": str(trace_path),
    }

    out_path = Path(args.out)
    out_path.write_text(json.dumps(qa, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(qa, indent=2))


if __name__ == "__main__":
    main()
