#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path


TRACE_RE = re.compile(
    r"/testbed/keras/src/quantizers/quantizers.py:(\d+) "
    r"keras\.src\.quantizers\.quantizers\.abs_max_quantize "
    r"event=(call|line|return)\b"
)


def extract_line_sequence(segment_text: str) -> list[int]:
    seq = []
    for line in segment_text.splitlines():
        m = TRACE_RE.search(line)
        if not m:
            continue
        seq.append(int(m.group(1)))
    return seq


def seq_hash(seq: list[int]) -> str:
    raw = json.dumps(seq, separators=(",", ":")).encode("utf-8")
    return hashlib.sha1(raw).hexdigest()[:16]


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--trace-log",
        default="/testbed/logs/qa_instances/quantizers_absmax_trace_profile_gamma/trace.log",
    )
    p.add_argument(
        "--out",
        default="/testbed/logs/qa_instances/quantizers_absmax_trace_profile_gamma/oracle.json",
    )
    args = p.parse_args()

    trace_text = Path(args.trace_log).read_text(encoding="utf-8")
    segments = [s for s in trace_text.split("[TRACE][START]") if s.strip()]

    sequences = [extract_line_sequence(segment) for segment in segments]
    sequences = [seq for seq in sequences if seq]

    holds = True
    counterexample = None
    if sequences:
        baseline = sequences[0]
        baseline_hash = seq_hash(baseline)
        for idx, seq in enumerate(sequences[1:], start=2):
            if seq != baseline:
                holds = False
                first_diff = 0
                max_len = max(len(baseline), len(seq))
                for i in range(max_len):
                    base_line = baseline[i] if i < len(baseline) else None
                    obs_line = seq[i] if i < len(seq) else None
                    if base_line != obs_line:
                        first_diff = i
                        break
                counterexample = {
                    "baseline_run_index": 1,
                    "run_index": idx,
                    "first_diff_index": first_diff,
                    "baseline_line": baseline[first_diff] if first_diff < len(baseline) else None,
                    "observed_line": seq[first_diff] if first_diff < len(seq) else None,
                    "baseline_path_hash": baseline_hash,
                    "observed_path_hash": seq_hash(seq),
                }
                break

    qa = {
        "question_kind": "determinism_flakiness",
        "question": (
            "Use `keras/src/test/quantizers/quantizers_absmax_trace_profile_gamma_test.py`, class "
            "`QuantizersAbsMaxTraceProfileGammaQATest`, method `test_single_dispatch_profile`. "
            "In `keras/src/quantizers/quantizers.py`, trace function `abs_max_quantize` and consider "
            "the ordered line-number sequence generated by `(event=call|line|return)` during that method. "
            "For repeated executions of this same test method, does this line-number path sequence remain "
            "exactly identical across all runs?"
        ),
        "oracle_answer": {
            "invariant_exists": holds,
            "num_segments": len(sequences),
            "num_observations": max(0, len(sequences) - 1),
            "counterexample": counterexample,
        },
    }

    Path(args.out).write_text(json.dumps(qa, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(qa, indent=2))


if __name__ == "__main__":
    main()
