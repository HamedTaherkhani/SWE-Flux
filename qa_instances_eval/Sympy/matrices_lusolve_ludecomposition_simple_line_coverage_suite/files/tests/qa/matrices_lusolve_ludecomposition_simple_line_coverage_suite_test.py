class TestMatricesLUSolveLUDecompositionSimpleLineCoverageSuiteQA:
    @pytest.mark.parametrize("a_rows,b_rows", CASES)
    def test_matrices_lusolve_ludecomposition_simple_line_coverage_suite_case(
        self, a_rows, b_rows
    ):
        a = Matrix(a_rows)
        b = Matrix(b_rows)

        # Indirect call: Matrix.LUsolve() triggers internal LU decomposition.
        x = a.LUsolve(b)

        assert x.shape[0] == a.cols
        assert x.shape[1] == b.shape[1]
        assert a * x == b
